/* Builds www/data/seed.js: the nsmart stop list + routes learned from live answers, so the app knows every route
 * from its first start. Uses the same engine code as the app. Polite: 1 nsmart request per second.
 *   node tools/crawl.js [passes=2] [stations.json]
 */
const fs = require('fs'), path = require('path'), vm = require('vm');
const WWW = path.join(__dirname, '..', 'www');
for (const f of ['net.js', 'nsmart.js', 'gspns.js', 'model.js']) vm.runInThisContext(fs.readFileSync(path.join(WWW, 'js', f), 'utf8'), { filename: f });
const T = globalThis.T, M = T.model, N = T.nsmart;

(async () => {
  const passes = +(process.argv[2] || 2);
  const stFile = process.argv[3];
  const seedFile = path.join(WWW, 'data', 'seed.js');
  if (fs.existsSync(seedFile)) vm.runInThisContext(fs.readFileSync(seedFile, 'utf8'));   // continue a previous crawl
  N.gate.minMs = 1000;
  if (stFile) M.stations = N.compactStations(JSON.parse(fs.readFileSync(stFile, 'utf8')));
  else if (T.SEED && T.SEED.stations) M.stations = T.SEED.stations;
  else M.stations = await N.fetchStations();
  M.stationsAt = (T.SEED && T.SEED.stationsAt && !stFile) ? T.SEED.stationsAt : Date.now();
  Object.assign(M.routes, (T.SEED && T.SEED.routes) || {});
  // line catalogue (same as model.buildLines; init() is not used here: it would start the app's poll loop)
  const G = T.gspns;
  const L = {};
  for (const uid of Object.keys(M.stations)) for (const line of M.stations[uid].l || []) {
    const b = G.base(line); const e = L[b] || (L[b] = { base: b, city: false, variants: [], stops: [] });
    if (String((M.stations[uid].t || {})[line]) === '1') e.city = true; e.stops.push(uid);
  }
  M.lines = L;
  console.log('stations', Object.keys(M.stations).length, 'lines', Object.keys(L).length, 'routes known', Object.keys(M.routes).length);
  for (let p = 0; p < passes; p++) {
    const plan = M.plan();
    console.log('pass', p + 1, 'polling', plan.length, 'stops');
    let buses = 0, errs = 0;
    for (let i = 0; i < plan.length; i++) {
      const r = await N.fetchStop(plan[i]);
      if (r.error) { errs++; continue; }
      buses += M.observe(r.buses, Date.now());
      if (i % 25 === 0) console.log('  ', i, '/', plan.length, 'routes', Object.keys(M.routes).length, 'vehicles', Object.keys(M.vehicles).length);
    }
    console.log('pass', p + 1, 'done: routes', Object.keys(M.routes).length, 'vehicles', Object.keys(M.vehicles).length, 'errors', errs);
  }
  const routes = {};
  for (const [k, r] of Object.entries(M.routes)) routes[k] = { k: r.k, line: r.line, dir: r.dir, actual: r.actual, title: r.title, dest: r.dest, s: r.s, t: r.t };
  const seed = { stationsAt: M.stationsAt, stations: M.stations, routes };
  fs.mkdirSync(path.dirname(seedFile), { recursive: true });
  fs.writeFileSync(seedFile, '/* generated by tools/crawl.js */\nT.SEED = ' + JSON.stringify(seed) + ';\n');
  const bases = {}; for (const r of Object.values(routes)) (bases[r.base || G.base(r.line)] = bases[r.base || G.base(r.line)] || new Set()).add(r.dir);
  const missing = Object.keys(L).filter(b => !bases[b]).sort(G.lineSort);
  const oneDir = Object.keys(bases).filter(b => bases[b].size < 2).sort(G.lineSort);
  console.log('seed written', fs.statSync(seedFile).size, 'bytes; routes', Object.keys(routes).length);
  console.log('lines without any route:', missing.join(' '));
  console.log('lines with one direction only:', oneDir.join(' '));
  process.exit(0);
})().catch(e => { console.error(e); process.exit(1); });
